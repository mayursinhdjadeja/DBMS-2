--  Write a trigger to restrict users from accessing the table on weekends. 

SET SERVEROUTPUT ON;
CREATE OR REPLACE TRIGGER RESTRICT_WEEKEND_ACCESS
BEFORE INSERT OR UPDATE OR DELETE
ON EMP
BEGIN
    IF TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH') IN ('SAT', 'SUN') THEN
        RAISE_APPLICATION_ERROR
        (
            -20001,
            'ACCESS TO EMPLOYEE TABLE IS NOT ALLOWED ON WEEKENDS'
        );
    END IF;
END;
